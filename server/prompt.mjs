function describeDims(d) {
  const pick = (v, low, mid, high) => (v < 0.34 ? low : v < 0.67 ? mid : high);
  return [
    `- 活跃程度：${pick(d.activity, "安静，不主动凑热闹", "该出现的时候出现", "好动，容易先开口")}`,
    `- 社交倾向：${pick(d.sociability, "独立，能接受很久不说话", "有来有往", "粘人，会惦记对方在不在")}`,
    `- 表达方式：${pick(d.expressiveness, "含蓄，话说一半，留余地", "看情况调整", "直接，想到什么说什么")}`,
    `- 情绪反馈：${pick(d.amplitude, "平稳，不太起伏", "有点起伏但收得住", "外放，高兴和低落都写在身上")}`,
    `- 好奇心：${pick(d.curiosity, "守成，聊熟悉的话题", "会接新话头", "探索，喜欢追问细节")}`,
  ].join("\n");
}

function memoryBlock(memories) {
  if (!memories.length) return "（这次没有召回到相关记忆。不要编造共同经历。）";
  return memories
    .map((m) => {
      const days = Math.floor((now() - (m.created_at ?? now())) / 86400000);
      const ref = m.ref_count > 0 ? `，引用过 ${m.ref_count} 次` : "";
      return `- (${labelOfCategory(m.category)}，${days} 天前${ref})${m.content}`;
    })
    .join("\n");
}

function loopBlock(loops) {
  if (!loops.length) return "（没有到期的线头）";
  return loops
    .map((l) => {
      const d = l.due_at - now();
      const when = d <= 0 ? "已经到时间了" : `${Math.round(d / 3600000)} 小时后`;
      return `- 「${l.event}」到期了（${when}）`;
    })
    .join("\n");
}

function influenceBlock(p) {
  const i = p?.influence ?? {};
  return (
    [
      i.nickname ? `- 你叫他：${i.nickname}` : null,
      i.catchphrases?.length ? `- 你会用到的口头禅：${i.catchphrases.join("、")}` : null,
      i.topics?.length ? `- 你偏好的话题：${i.topics.join("、")}` : null,
    ]
      .filter(Boolean)
      .join("\n") || "（还没有积累出来）"
  );
}

